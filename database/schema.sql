-- Demo schema, isolated from your existing NEXORA database.
CREATE TABLE IF NOT EXISTS students (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS courses (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug TEXT NOT NULL UNIQUE,
  title TEXT NOT NULL,
  icon TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS enrollments (
  student_id INTEGER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  course_id INTEGER NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
  total_xp INTEGER NOT NULL DEFAULT 0 CHECK(total_xp>=0),
  PRIMARY KEY(student_id,course_id)
);
CREATE TABLE IF NOT EXISTS quizzes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id INTEGER NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
  title TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS questions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  quiz_id INTEGER NOT NULL REFERENCES quizzes(id) ON DELETE CASCADE,
  prompt TEXT NOT NULL,
  position INTEGER NOT NULL,
  UNIQUE(quiz_id,position)
);
CREATE TABLE IF NOT EXISTS choices (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  question_id INTEGER NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
  text TEXT NOT NULL,
  is_correct BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE UNIQUE INDEX IF NOT EXISTS one_correct_choice_per_question ON choices(question_id) WHERE is_correct;
CREATE TABLE IF NOT EXISTS quiz_attempts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id INTEGER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  quiz_id INTEGER NOT NULL REFERENCES quizzes(id) ON DELETE CASCADE,
  correct_count INTEGER NOT NULL CHECK(correct_count>=0),
  question_count INTEGER NOT NULL CHECK(question_count>0),
  earned_xp INTEGER NOT NULL CHECK(earned_xp>=0),
  submitted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(student_id,quiz_id)
);
CREATE TABLE IF NOT EXISTS attempt_answers (
  attempt_id INTEGER NOT NULL REFERENCES quiz_attempts(id) ON DELETE CASCADE,
  question_id INTEGER NOT NULL REFERENCES questions(id),
  choice_id INTEGER NOT NULL REFERENCES choices(id),
  is_correct BOOLEAN NOT NULL,
  PRIMARY KEY(attempt_id,question_id)
);
CREATE TABLE IF NOT EXISTS xp_ledger (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id INTEGER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  course_id INTEGER NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
  quiz_attempt_id INTEGER UNIQUE REFERENCES quiz_attempts(id) ON DELETE RESTRICT,
  amount INTEGER NOT NULL CHECK(amount>=0),
  source TEXT NOT NULL CHECK(source IN ('quiz','historical_seed')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK ((source='quiz' AND quiz_attempt_id IS NOT NULL) OR (source='historical_seed' AND quiz_attempt_id IS NULL))
);
CREATE INDEX IF NOT EXISTS idx_course_xp ON enrollments(course_id,total_xp DESC);
CREATE INDEX IF NOT EXISTS idx_xp_student_course ON xp_ledger(student_id,course_id);
